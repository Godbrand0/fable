"""Build animated sprite sheets for every enemy from the code-drawn poses.

    python art/enemies/build_enemy_sheets.py public/sprites game/systems/enemySpriteManifest.ts [--preview out.png]

Writes public/sprites/enemy_<key>.png (frames left to right: move ×4, attack ×3,
hurt ×2, death ×3) and a TypeScript manifest the game reads at boot.
"""
import sys, colorsys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
import pixelkit as K, imp as I, minions as M, bosses as B

OUT, MANIFEST = Path(sys.argv[1]), Path(sys.argv[2])
PREVIEW = sys.argv[sys.argv.index('--preview') + 1] if '--preview' in sys.argv else None

def rgba(c): return K.render_rgba(c)

def shift(img, dy=0, dx=0):
    out = np.zeros_like(img)
    h, w = img.shape[:2]
    ys, ye = max(0, dy), min(h, h + dy)
    xs, xe = max(0, dx), min(w, w + dx)
    out[ys:ye, xs:xe] = img[ys - dy:ye - dy, xs - dx:xe - dx]
    return out

def bob(img, offs): return [shift(img, dy=o) for o in offs]

def recolor(img, hue_shift, sat=1.0, val=1.0, special=None):
    out = img.copy()
    a = img[..., 3] > 0
    for y, x in zip(*np.where(a)):
        r, g, b = img[y, x, :3] / 255.0
        h, s, v = colorsys.rgb_to_hsv(r, g, b)
        if special:
            hit = special(h, s, v)
            if hit is not None:
                out[y, x, :3] = hit; continue
        h = (h + hue_shift / 360.0) % 1.0
        r2, g2, b2 = colorsys.hsv_to_rgb(h, min(1, s * sat), min(1, v * val))
        out[y, x, :3] = (int(r2 * 255), int(g2 * 255), int(b2 * 255))
    return out

# key: (move frames, attack, hurt, death) as RGBA arrays
def imp_frames():
    def flap(wu):
        c = K.Canvas(I.W, I.H); I.standing(c, K.xf(pivot=(20, 30), dy=-1.5), wing_up=wu); return rgba(c)
    move = [flap(0), shift(flap(2), dy=-1), shift(flap(3), dy=-1), flap(1)]
    return move, rgba(I.attack()), rgba(I.hurt()), rgba(I.death())

def simple(ready, attack, hurt, death, offs=(0, -1, -1, 0)):
    r = rgba(ready())
    return bob(r, offs), rgba(attack()), rgba(hurt()), rgba(death())

CAST = {
    'imp':              imp_frames,
    'poison_slime':     lambda: ([rgba(M.slime_ready(q)) for q in (0, 1, 1.6, 1)], rgba(M.slime_attack()), rgba(M.slime_hurt()), rgba(M.slime_death())),
    'obsidian_golem':   lambda: simple(M.golem_ready, M.golem_attack, M.golem_hurt, M.golem_death, (0, 1, 0, 1)),
    'frost_wisp':       lambda: ([shift(rgba(M.wisp_ready(o)), dy=d) for o, d in ((0, 0), (1, -1), (0, -2), (-1, -1))], rgba(M.wisp_attack()), rgba(M.wisp_hurt()), rgba(M.wisp_death())),
    'storm_sentinel':   lambda: simple(M.sentinel_ready, M.sentinel_attack, M.sentinel_hurt, M.sentinel_death, (0, 1, 0, 1)),
    'sand_wraith':      lambda: simple(B.wraith_ready, B.wraith_attack, B.wraith_hurt, B.wraith_death, (0, -1, -2, -1)),
    'lava_pumpkin':     lambda: simple(B.pumpkin_ready, B.pumpkin_attack, B.pumpkin_hurt, B.pumpkin_death, (0, 1, 0, 1)),
    'swamp_hydra':      lambda: simple(B.hydra_ready, B.hydra_attack, B.hydra_hurt, B.hydra_death, (0, -1, 0, 1)),
    'fire_demon':       lambda: simple(B.demon_ready, B.demon_attack, B.demon_hurt, B.demon_death, (0, -1, -2, -1)),
    'glacier_wyrm':     lambda: simple(B.wyrm_ready, B.wyrm_attack, B.wyrm_hurt, B.wyrm_death, (0, -1, 0, 1)),
    'thunder_colossus': lambda: simple(B.colossus_ready, B.colossus_attack, B.colossus_hurt, B.colossus_death, (0, 1, 0, 1)),
}

def void_imp():
    m, a, h, d = imp_frames()
    eyes = lambda hh, s, v: (210, 160, 255) if (0.05 < hh < 0.17 and s > 0.6 and v > 0.8) else None   # orange/yellow eyes → lilac
    f = lambda img: recolor(img, 268, sat=0.85, val=0.62, special=eyes)
    return [f(x) for x in m], f(a), f(h), f(d)

def void_titan():
    m, a, h, d = CAST['thunder_colossus']()
    eyes = lambda hh, s, v: (220, 170, 255) if (0.1 < hh < 0.18 and s > 0.5) else None                 # yellow → lilac
    f = lambda img: recolor(img, 55, sat=1.2, val=0.85, special=eyes)
    return [f(x) for x in m], f(a), f(h), f(d)

CAST['void_imp'] = void_imp
CAST['void_titan'] = void_titan

ANIMS = {'move': (0, 4, 6, -1), 'attack': (4, 3, 10, 0), 'hurt': (7, 2, 12, 0), 'death': (9, 3, 6, 0)}

entries, previews = [], []
for key, fn in CAST.items():
    move, attack, hurt, death = fn()
    ready = move[0]
    frames = move + [attack, attack, ready] + [hurt, hurt] + [hurt, death, death]
    fh, fw = frames[0].shape[:2]
    sheet = np.concatenate(frames, axis=1)
    Image.fromarray(sheet).save(OUT / f'enemy_{key}.png')
    entries.append(f"  {key}: {{ frameWidth: {fw}, frameHeight: {fh} }},")
    previews.append((key, [ready, attack, hurt, death]))
    print(f'{key:18s} {fw}x{fh}  {len(frames)} frames')

MANIFEST.write_text(f"""// GENERATED by art/enemies/build_enemy_sheets.py — do not edit by hand.
// One sprite sheet per enemy at /sprites/enemy_<key>.png. Every sheet has the
// same frame layout: move ×4, attack ×3, hurt ×2, death ×3.

export const ENEMY_SHEETS: Record<string, {{ frameWidth: number; frameHeight: number }}> = {{
{chr(10).join(entries)}
}};

/** [first frame, frame count, frame rate, repeat] per animation. */
export const ENEMY_ANIMS = {{
{chr(10).join(f"  {k}: {{ start: {s}, count: {n}, frameRate: {r}, repeat: {rep} }}," for k, (s, n, r, rep) in ANIMS.items())}
}} as const;
""")

if PREVIEW:
    rows = []
    for key, fr in previews:
        rows.append(K.sheet([np.where(f[..., 3:4] > 0, f[..., :3], np.array([60, 66, 74], np.uint8)) for f in fr], upscale=2, bg=(60, 66, 74)))
    W = max(r.width for r in rows); Hh = sum(r.height for r in rows)
    out = Image.new('RGB', (W, Hh), (60, 66, 74)); y = 0
    for r in rows: out.paste(r, (0, y)); y += r.height
    out.save(PREVIEW)
